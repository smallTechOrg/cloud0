-- Daily cost (SMA-29). The billing query also groups by DATE(usage_start_time);
-- each weekly snapshot keeps its per-day rows here, at the same grain as
-- snapshot_rows plus usage_date, so daily charts can be broken down by
-- service, project, product or environment. Snapshots fetched before this
-- migration have no daily rows (the daily endpoint reports them as such).
CREATE TABLE snapshot_daily_rows (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id          BIGINT  NOT NULL REFERENCES snapshots (id) ON DELETE CASCADE,
    usage_date           TEXT    NOT NULL,
    project_id           TEXT    NOT NULL,
    service              TEXT    NOT NULL,
    sku                  TEXT    NOT NULL,
    resource_name        TEXT    NULL,
    resource_global_name TEXT    NULL,
    labels_json          TEXT    NULL,
    gross                DOUBLE PRECISION NOT NULL,
    credits              DOUBLE PRECISION NOT NULL,
    net                  DOUBLE PRECISION NOT NULL
);
CREATE INDEX idx_snapshot_daily_rows_snapshot ON snapshot_daily_rows (snapshot_id, usage_date);

