-- Mirrors migrations/0001_init.sql step for step: SQLite's INTEGER PRIMARY KEY
-- AUTOINCREMENT is an identity column, INTEGER is BIGINT and REAL is DOUBLE
-- PRECISION (both 64-bit in SQLite), timestamps stay RFC3339 TEXT and flags
-- stay INTEGER 0/1, so every query is shared between the two dialects.

CREATE TABLE runs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "trigger"       TEXT    NOT NULL CONSTRAINT runs_trigger_check CHECK ("trigger" IN ('refresh_week', 'refresh_all')),
    from_iso_year   BIGINT  NOT NULL,
    from_iso_week   BIGINT  NOT NULL,
    to_iso_year     BIGINT  NOT NULL,
    to_iso_week     BIGINT  NOT NULL,
    started_at      TEXT    NOT NULL,
    finished_at     TEXT    NULL,
    duration_ms     BIGINT  NULL,
    status          TEXT    NOT NULL CHECK (status IN ('running', 'ok', 'partial', 'failed')),
    error           TEXT    NULL,
    created_at      TEXT    NOT NULL
);
CREATE INDEX idx_runs_started_at ON runs (started_at DESC);

CREATE TABLE run_sources (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id          BIGINT  NOT NULL REFERENCES runs (id) ON DELETE CASCADE,
    source          TEXT    NOT NULL,
    status          TEXT    NOT NULL CHECK (status IN ('ok', 'failed')),
    started_at      TEXT    NOT NULL,
    finished_at     TEXT    NOT NULL,
    duration_ms     BIGINT  NOT NULL,
    sql_text        TEXT    NOT NULL,
    params_json     TEXT    NOT NULL,
    job_id          TEXT    NULL,
    bytes_processed BIGINT  NULL,
    bytes_billed    BIGINT  NULL,
    cache_hit       BIGINT  NULL,
    rows_returned   BIGINT  NULL,
    error_code      TEXT    NULL,
    error_message   TEXT    NULL,
    fix_hint        TEXT    NULL
);
CREATE INDEX idx_run_sources_run_id ON run_sources (run_id);

CREATE TABLE snapshots (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iso_year        BIGINT  NOT NULL,
    iso_week        BIGINT  NOT NULL,
    week_start      TEXT    NOT NULL,
    week_end        TEXT    NOT NULL,
    fetched_at      TEXT    NOT NULL,
    status_at_fetch TEXT    NOT NULL CHECK (status_at_fetch IN ('partial', 'settling', 'final')),
    run_id          BIGINT  NOT NULL REFERENCES runs (id),
    run_source_id   BIGINT  NOT NULL REFERENCES run_sources (id),
    row_count       BIGINT  NOT NULL,
    gross_total     DOUBLE PRECISION NOT NULL,
    credits_total   DOUBLE PRECISION NOT NULL,
    net_total       DOUBLE PRECISION NOT NULL,
    created_at      TEXT    NOT NULL
);
CREATE INDEX idx_snapshots_week_latest ON snapshots (iso_year, iso_week, id DESC);
CREATE INDEX idx_snapshots_run_id ON snapshots (run_id);

CREATE TABLE snapshot_rows (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id          BIGINT  NOT NULL REFERENCES snapshots (id) ON DELETE CASCADE,
    project_id           TEXT    NOT NULL,
    service_id           TEXT    NOT NULL DEFAULT '',
    service              TEXT    NOT NULL,
    sku_id               TEXT    NOT NULL DEFAULT '',
    sku                  TEXT    NOT NULL,
    resource_name        TEXT    NULL,
    resource_global_name TEXT    NULL,
    gross                DOUBLE PRECISION NOT NULL,
    credits              DOUBLE PRECISION NOT NULL,
    net                  DOUBLE PRECISION NOT NULL,
    line_items           BIGINT  NOT NULL
);
CREATE INDEX idx_snapshot_rows_service ON snapshot_rows (snapshot_id, service);
CREATE INDEX idx_snapshot_rows_service_sku ON snapshot_rows (snapshot_id, service, sku);
CREATE INDEX idx_snapshot_rows_project ON snapshot_rows (snapshot_id, project_id);

CREATE TABLE annotations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iso_year    BIGINT  NOT NULL,
    iso_week    BIGINT  NOT NULL,
    body        TEXT    NOT NULL,
    created_at  TEXT    NOT NULL,
    updated_at  TEXT    NOT NULL,
    UNIQUE (iso_year, iso_week)
);

CREATE TABLE settings (
    "key"       TEXT PRIMARY KEY,
    value       TEXT NOT NULL,
    updated_at  TEXT NOT NULL
